def _badge_class(tip_prob):
    if pd.isna(tip_prob):
        return "med"
    if tip_prob >= 0.70:
        return "hi"
    if tip_prob >= 0.55:
        return "med"
    return "lo"


def _page(title, subtitle, body, generated_note=True):
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    footer = f"Generated by Footy Tipper on {stamp}. Tips are for bragging rights, not financial advice." if generated_note else ""
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(title)}</title>
<style>{_PAGE_CSS}</style>
</head>
<body>
<div class="wrap">
<header class="site">
<h1>Footy Tipper</h1>
<p>{html.escape(subtitle)}</p>
</header>
<nav><a href="index.html">This Round</a><a href="results.html">Season Results</a></nav>
{body}
<footer>{footer}</footer>
</div>
</body>
</html>
"""


def _scoreboard_card(scoreboard):
    if not isinstance(scoreboard, dict):
        return ""
    stats = [
        (f"{scoreboard['last_round_correct']}/{scoreboard['last_round_games']}", scoreboard["last_round_name"]),
        (
            f"{scoreboard['season_correct']}/{scoreboard['season_games']} ({scoreboard['season_accuracy']:.0%})",
            "Season",
        ),
    ]
    if scoreboard.get("market_accuracy") is not None:
        stats.append((f"{scoreboard['market_accuracy']:.0%}", "Market favourite"))
    cells = "".join(
        f'<div class="stat"><div class="v">{html.escape(v)}</div><div class="l">{html.escape(label)}</div></div>'
        for v, label in stats
    )
    return f'<div class="card"><h2>The ledger</h2><div class="stats">{cells}</div></div>'


def _tips_card(predictions):
    if predictions.empty:
        return (
            '<div class="card"><h2>This round</h2>'
            "<p>No upcoming pre-game fixtures right now. Check back when the next round's team lists drop.</p></div>"
        )

    rows = []
    for _, row in predictions.iterrows():
        winner = _prediction_winner(row)
        tip_prob = tip_probability(row)
        rows.append(
            "<tr>"
            f"<td>{html.escape(str(row['team_home']))} vs {html.escape(str(row['team_away']))}</td>"
            f"<td class=\"tip\">{html.escape(str(winner))}</td>"
            f"<td><span class=\"badge {_badge_class(tip_prob)}\">{_format_probability(tip_prob)}</span></td>"
            f"<td>{html.escape(_format_predicted_score_numbers(row))}</td>"
            f"<td>{html.escape(_format_predicted_margin(row))}</td>"
            f"<td>H {_format_market_price(row['team_head_to_head_odds_home'], row.get('market_odds_fresh', True))}"
            f" / A {_format_market_price(row['team_head_to_head_odds_away'], row.get('market_odds_fresh', True))}</td>"
            "</tr>"
        )
    round_name = predictions["round_name"].iloc[0]
    year = predictions["competition_year"].iloc[0]
    market_notice = _market_coverage_notice(predictions)
    market_notice_html = ""
    if market_notice:
        market_notice_html = (
            '<p style="padding:10px 12px; border:1px solid #fdba74; '
            'border-radius:8px; background:#fff7ed; color:#9a3412;">'
            f"<strong>Market data notice:</strong> {html.escape(market_notice)}</p>"
        )
    return (
        f'<div class="card"><h2>{html.escape(str(round_name))} {html.escape(str(year))} tips</h2>'
        f"{market_notice_html}"
        "<table><thead><tr><th>Fixture</th><th>Tip</th><th>Confidence</th><th>Score tip</th>"
        "<th>Margin</th><th>H2H odds</th></tr></thead>"
        f"<tbody>{''.join(rows)}</tbody></table></div>"
    )


def _value_card(tipper_picks):
    if tipper_picks.empty:
        return '<div class="card"><h2>Value picks</h2><p>None flagged this round.</p></div>'
    rows = []
    for _, row in tipper_picks.iterrows():
        rows.append(
            "<tr>"
            f"<td>{html.escape(str(row['team']))} vs {html.escape(str(row['opponent']))}</td>"
            f"<td>{_format_price(row['price'])}</td>"
            f"<td>{_format_price(row['price_min'])}</td>"
            f"<td>{float(row['edge']):.1%}</td>"
            f"<td>{float(row['stake_fraction']):.1%}</td>"
            "</tr>"
        )
    return (
        '<div class="card"><h2>Value picks</h2>'
        "<table><thead><tr><th>Team</th><th>Market</th><th>Fair</th><th>Edge</th><th>Stake share</th></tr></thead>"
        f"<tbody>{''.join(rows)}</tbody></table></div>"
    )


def _joker_card(joker_recommendation):
    if not isinstance(joker_recommendation, dict):
        return ""
    headline = html.escape(str(joker_recommendation.get("headline", "Joker call unavailable")))
    body = "".join(f"<p>{html.escape(line)}</p>" for line in _joker_reader_lines(joker_recommendation))
    play_class = " play" if joker_recommendation.get("should_use_this_round") else ""
    return f'<div class="card"><h2>Joker round call</h2><div class="joker{play_class}"><h3>{headline}</h3>{body}</div></div>'


def _results_card(results):
    if results.empty:
        return '<div class="card"><h2>Season results</h2><p>No settled predicted games yet this season.</p></div>'

    rows = []
    for _, row in results.iterrows():
        if bool(row.get("is_draw", False)):
            outcome = '<span class="badge med">Draw</span>'
        elif bool(row["tip_correct"]):
            outcome = '<span class="hit">&#10003;</span>'
        else:
            outcome = '<span class="miss">&#10007;</span>'
        score = f"{int(row['team_final_score_home'])}&ndash;{int(row['team_final_score_away'])}"
        rows.append(
            "<tr>"
            f"<td>{html.escape(str(row['round_name'] or f'Round {int(row.round_id)}'))}</td>"
            f"<td>{html.escape(str(row['team_home']))} vs {html.escape(str(row['team_away']))}</td>"
            f"<td class=\"tip\">{html.escape(str(row['tipped_team']))} ({_format_probability(row['tip_prob'])})</td>"
            f"<td>{score}</td>"
            f"<td>{outcome}</td>"
            "</tr>"
        )
    return (
        '<div class="card"><h2>Season results</h2>'
        "<table><thead><tr><th>Round</th><th>Fixture</th><th>Tip</th><th>Score</th><th>Hit</th></tr></thead>"
        f"<tbody>{''.join(rows)}</tbody></table></div>"
    )


def generate_site(db_path, project_root):
    """Render docs/site/ pages. Returns the list of files written."""
    project_root = Path(project_root)
    site_dir = project_root / "docs" / "site"
    rounds_dir = site_dir / "rounds"
    site_dir.mkdir(parents=True, exist_ok=True)
    rounds_dir.mkdir(parents=True, exist_ok=True)

    predictions = get_predictions(db_path, project_root)
    tipper_picks = get_tipper_picks(predictions) if not predictions.empty else pd.DataFrame()
    joker = get_joker_round_recommendation(db_path, project_root, predictions) if not predictions.empty else None
    scoreboard = get_season_scoreboard(db_path)
    results = get_season_results(db_path)

    if not predictions.empty:
        round_name = str(predictions["round_name"].iloc[0])
        year = predictions["competition_year"].iloc[0]
        subtitle = f"{round_name} {year} — machine-made NRL tips"
    else:
        subtitle = "Machine-made NRL tips"

    index_body = (
        _scoreboard_card(scoreboard)
        + _tips_card(predictions)
        + _value_card(tipper_picks)
        + _joker_card(joker)
    )
    index_html = _page("Footy Tipper — This Round", subtitle, index_body)

    written = []
    index_path = site_dir / "index.html"
    index_path.write_text(index_html, encoding="utf-8")
    written.append(index_path)

    if not predictions.empty:
        try:
            year_val = int(predictions["competition_year"].iloc[0])
            round_val = int(predictions["round_id"].iloc[0])
            round_path = rounds_dir / f"{year_val}-round-{round_val}.html"
            round_path.write_text(index_html, encoding="utf-8")
            written.append(round_path)
        except Exception as exc:
            print(f"Round archive page skipped ({exc}).")

    results_body = _scoreboard_card(scoreboard) + _results_card(results)
    results_path = site_dir / "results.html"
    results_path.write_text(_page("Footy Tipper — Season Results", subtitle, results_body), encoding="utf-8")
    written.append(results_path)

    for path in written:
        print(f"Site page written: {path.relative_to(project_root)}")
    return written


def publish_site(project_root):
    """Commit and push docs/site/. No-op when there is nothing to commit."""
    project_root = Path(project_root)
    try:
        status = subprocess.run(
            ["git", "status", "--porcelain", "docs/site"],
            cwd=project_root, capture_output=True, text=True, check=True,
        ).stdout.strip()
        if not status:
            print("Site publish: nothing to commit.")
            return True
        subprocess.run(["git", "add", "docs/site"], cwd=project_root, check=True)
        subprocess.run(
            ["git", "commit", "-m", "Publish tips site update"],
            cwd=project_root, check=True,
        )
        subprocess.run(["git", "push"], cwd=project_root, check=True)
        print("Site publish: committed and pushed docs/site.")
        return True
    except subprocess.CalledProcessError as exc:
        print(f"Site publish failed ({exc}).")
        return False
